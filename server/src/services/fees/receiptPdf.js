// Printed fee receipt (PDF), built with pdfkit. English only in this version: the standard font has no Devanagari glyphs,
// so Nepali text is not printed yet. Amounts use NPR with Nepali grouping (money.js).
import PDFDocument from 'pdfkit';
import { formatNPR } from './money.js';
import { registerPdfFonts } from '../pdf/fonts.js';

const LEFT = 50;
const RIGHT = 545;
const money = p => formatNPR(p);

// The receipt date is the school's date (Asia/Kathmandu). A payment recorded between 00:00 and 05:45 Nepal
// time is still the same Nepal day, even though its UTC timestamp is the day before.
export function receiptDate(utcStamp) {
  const d = new Date(String(utcStamp).replace(' ', 'T') + 'Z');
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kathmandu', year: 'numeric', month: '2-digit', day: '2-digit' }).format(d);
}

export function renderReceiptPdf(r, { compress = true } = {}) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A4', margin: LEFT, compress,
      info: { Title: `Fee receipt ${r.receipt_no}`, Author: r.school_name || 'School', Creator: 'NITEX fee system' },
    });
    registerPdfFonts(doc);
    const chunks = [];
    doc.on('data', c => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const line = (label, value, { bold = false } = {}) => {
      const y = doc.y;
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(10);
      doc.text(label, LEFT, y, { width: 200 });
      doc.text(value ?? '-', LEFT + 200, y, { width: RIGHT - LEFT - 200, align: 'right' });
      doc.moveDown(0.35);
    };
    const heading = text => {
      doc.moveDown(0.6);
      doc.font('Helvetica-Bold').fontSize(11).text(text, LEFT, doc.y, { width: RIGHT - LEFT });
      doc.moveDown(0.3);
    };

    doc.font('Helvetica-Bold').fontSize(16).text(r.school_name || 'School', LEFT, doc.y, { width: RIGHT - LEFT, align: 'center' });
    doc.font('Helvetica').fontSize(12).text('Fee receipt', { width: RIGHT - LEFT, align: 'center' });
    doc.moveDown(0.8);

    line('Receipt no', String(r.receipt_no), { bold: true });
    line('Date', receiptDate(r.date));
    line('Status', r.status);
    line('Invoice', `${r.invoice_no}${r.period ? ` (${r.period})` : ''}`);

    heading('Student');
    line('Name', r.student.name);
    line('Class and section', `${r.student.class_level ?? '-'} ${r.student.section ?? ''}`.trim());
    if (r.student.roll_no) line('Roll no', String(r.student.roll_no));

    heading('Invoice breakdown');
    const cols = { name: LEFT, gross: 300, conc: 390, net: 470 };
    const y0 = doc.y;
    doc.font('Helvetica-Bold').fontSize(9);
    doc.text('Fee head', cols.name, y0, { width: 240 });
    doc.text('Gross', cols.gross, y0, { width: 80, align: 'right' });
    doc.text('Concession', cols.conc, y0, { width: 70, align: 'right' });
    doc.text('Net', cols.net, y0, { width: RIGHT - cols.net, align: 'right' });
    doc.moveDown(0.5);
    doc.font('Helvetica').fontSize(9);
    for (const it of r.items) {
      const y = doc.y;
      doc.text(it.name, cols.name, y, { width: 240 });
      doc.text(money(it.gross_paisa), cols.gross, y, { width: 80, align: 'right' });
      doc.text(money(it.concession_paisa), cols.conc, y, { width: 70, align: 'right' });
      doc.text(money(it.net_paisa), cols.net, y, { width: RIGHT - cols.net, align: 'right' });
      doc.moveDown(0.4);
    }
    doc.moveDown(0.3);
    line('Invoice net amount', money(r.invoice.net_paisa));
    line('Paid to date', money(r.invoice.paid_paisa));
    line('Balance due', money(r.invoice.balance_paisa), { bold: true });
    if (r.invoice.credit_balance_paisa > 0) line('Credit on student account', money(r.invoice.credit_balance_paisa));

    heading('This payment');
    line('Amount received', money(r.amount_paisa), { bold: true });
    line('Method', r.method);
    if (r.reference) line('Reference', r.reference);
    if (r.refunded_paisa > 0) line('Refunded so far', money(r.refunded_paisa));
    line('Processed by', r.processed_by || '-');
    if (r.verified_by) line('Verified by', r.verified_by);

    doc.moveDown(1.2);
    doc.font('Helvetica').fontSize(8).fillColor('#555555').text(
      'All amounts are in NPR. This receipt was generated by the school fee system. Keep it for your records.',
      LEFT, doc.y, { width: RIGHT - LEFT, align: 'center' });
    doc.end();
  });
}
